CREATE TABLE USUARIO (
  ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME VARCHAR2(120) NOT NULL,
  EMAIL VARCHAR2(160) NOT NULL,
  SENHA_HASH VARCHAR2(500) NOT NULL,
  TIPO_USUARIO NUMBER(2) DEFAULT 1 NOT NULL,
  ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT UX_USUARIO_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE PONTO_CRITICO (
  ID_PONTO_CRITICO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOME VARCHAR2(140) NOT NULL,
  TIPO NUMBER(2) NOT NULL,
  DESCRICAO VARCHAR2(400), ENDERECO VARCHAR2(250),
  LATITUDE NUMBER(10,7) NOT NULL, LONGITUDE NUMBER(10,7) NOT NULL,
  ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE RELATO (
  ID_RELATO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_USUARIO NUMBER NOT NULL,
  ID_PONTO_CRITICO NUMBER NOT NULL,
  TIPO NUMBER(2) NOT NULL,
  DESCRICAO VARCHAR2(600) NOT NULL,
  LATITUDE NUMBER(10,7) NOT NULL, LONGITUDE NUMBER(10,7) NOT NULL,
  STATUS NUMBER(2) DEFAULT 1 NOT NULL,
  DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  DATA_ULTIMA_CONFIRMACAO TIMESTAMP NULL,
  DATA_RESOLUCAO TIMESTAMP NULL,
  CONSTRAINT FK_RELATO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
  CONSTRAINT FK_RELATO_PONTO FOREIGN KEY (ID_PONTO_CRITICO) REFERENCES PONTO_CRITICO(ID_PONTO_CRITICO)
);

CREATE TABLE CONFIRMACAO_RELATO (
  ID_CONFIRMACAO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ID_RELATO NUMBER NOT NULL,
  ID_USUARIO NUMBER NOT NULL,
  DATA_CONFIRMACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT FK_CONF_RELATO FOREIGN KEY (ID_RELATO) REFERENCES RELATO(ID_RELATO) ON DELETE CASCADE,
  CONSTRAINT FK_CONF_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
  CONSTRAINT UX_CONF_RELATO_USUARIO UNIQUE (ID_RELATO, ID_USUARIO)
);

